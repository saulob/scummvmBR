#!/usr/bin/env python3
# Converts a Bink video into scummbr_intro.inc, the byte array that
# AGOSEngine::playScummBRIntro() plays before Simon 1 and Simon 2 start.
#
# Usage: python scummbr_intro.py <video.bik>
#
# Run it again whenever the video changes, then rebuild ScummVM.

import os
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: python scummbr_intro.py <video.bik>')

    src = sys.argv[1]
    with open(src, 'rb') as f:
        data = f.read()

    if data[:3] != b'BIK':
        sys.exit('error: %s is not a Bink video' % src)

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scummbr_intro.inc')
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by scummbr_intro.py from %s. Do not edit.\n' % os.path.basename(src))
        f.write('static const uint32 kScummBRIntroBikSize = %d;\n' % len(data))
        f.write('static const byte kScummBRIntroBik[%d] = {\n' % len(data))
        for i in range(0, len(data), 16):
            row = ', '.join('0x%02X' % b for b in data[i:i + 16])
            f.write('\t%s,\n' % row)
        f.write('};\n')

    print('wrote %s (%d bytes of video)' % (out, len(data)))


if __name__ == '__main__':
    main()
